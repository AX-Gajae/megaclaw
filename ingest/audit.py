    # 이제 `paper_dead()` 와 **같은 수집기**(`paper_bodies` + `meta_body_text`)를 쓴다
    # --- 두 벌로 적으면 갈라진다(노트 701·713 이 등록소로 고친 병).
    srcs_text, unread = [], []
