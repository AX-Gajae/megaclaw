        for m in _re.finditer(_re.escape(dead), line):
            nxt = line[m.end():m.end() + 1]
            prv = line[m.start() - 1:m.start()] if m.start() else ""
            if nxt.isdigit() or prv.isdigit():
                continue                      # 더 긴 숫자의 일부다
