            # 구별이 안 됐다**(조항 59). `runners/**/*` 에는 이진 산출물이 섞여 있어
            # 실패로 세면 게이트가 꺼지므로, 실패로는 안 세되 **보이게** 올린다.
            unread.append({"문서": rel, "왜": type(e).__name__})
