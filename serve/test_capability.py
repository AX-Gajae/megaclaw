"""`serve.capability.check` 회귀 시험 --- **검사를 세울 때 같이 세운다**(노트 676).

    python3 -m serve.test_capability

왜 이 파일이 있나. 노트 676 이 다섯 사례를 쟀다: **``통과''는 아무것도
말하지 않는다.** 검사가 무엇을 잡는지는 **실패를 심어야** 보인다. 그리고
`check` 는 문자열로 찾는 검사라 범위 문제를 네 번 밟았다 ---
노트 674(부분 문자열) · 677(숫자 경계) · 693(이름 범위) · 697(문맥).

**표의 절반은 통과해야 하는 줄이다.** 위반만 모으면 "다 잡는" 검사(항상 참)가
통과한다. 그래서 `False` 줄을 같은 수로 둔다.
"""
from __future__ import annotations

import sys

#: (글, 걸려야 하나, 왜 이 줄이 표에 있나)
CASES = [
    # ── 걸려야 하는 것 ────────────────────────────────────────────
    ("지금까지 82% 적중했습니다.", True, "전향 실적 단정"),
    ("우리 모델 적중률은 79% 입니다.", True, "전향 실적 단정(다른 표현)"),
    ("80% 확률로 8천~2만명입니다.", True,
     "이름 붙인 구간 --- '구간' 이라는 낱말이 없다(노트 697 에서 놓쳤던 줄)"),
    ("80% 구간은 12,000~34,000 입니다.", True, "이름 붙인 구간(기본형)"),
    ("90% 신뢰로 5만에서 8만 사이입니다.", True, "이름 붙인 구간(신뢰·사이)"),
    # ── 통과해야 하는 것 ──────────────────────────────────────────
    ('"지금까지 ○○% 적중했다" 같은 전향 실적은 말할 수 없습니다.', False,
     "**카드를 지키는 문장** --- 화면에 경고가 두 번 뜬 원인이었다(노트 697)"),
    ("전향 기록이 0건이라 적중률은 못 냅니다.", False, "부인문"),
    ("80% 구간이라는 이름은 실측 덮음 50.2% 라 못 씁니다.", False,
     "실측을 말하며 부인하는 문장"),
    ('"80% 확률로 8천~2만명" 같은 꼴은 안 냅니다.', False, "예시로 인용"),
    ("상위 18% 입니다.", False, "허용 꼴 --- 도메인 안 백분위"),
    ("각색 확률 51.1% 입니다.", False, "허용 꼴 --- 확률"),
    ("유보 AUC 0.9408 · 기저율 3.07% 입니다.", False, "자를 적는 문장"),
]


def main() -> int:
    from .capability import check
    bad = 0
    for text, want, why in CASES:
        got = bool(check(text))
        ok = got == want
        bad += not ok
        mark = "OK " if ok else "실패"
        print(f"{mark} {'걸려야' if want else '통과해야':>8s} · {text[:52]!r}")
        if not ok:
            print(f"     → 받은 것: {check(text) or '통과'}  ({why})")
    n = len(CASES)
    pos = sum(1 for _, w, _ in CASES if w)
    print(f"\n{n - bad}/{n} 통과 (걸려야 {pos} · 통과해야 {n - pos})")
    if bad:
        print("**실패가 있다.** `check` 의 범위를 다시 본다 --- "
              "문자열로 찾는 검사는 범위를 정해야 한다(노트 677·693·697)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
