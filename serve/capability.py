#: 금지 꼴을 **부인하거나 예시로 드는** 자리를 가르는 낱말. 이것이 같은 줄에
#: 있으면 위반이 아니다 --- 오히려 카드를 지키는 문장이다.
NEGATION = ("못", "없", "아니", "안 ", "안다", "금지", "말할 수", "쓰면 안",
            "거짓", "빼", "제외", "대신", "예:", "같은", "따위", "형태를")


def _asserted(text: str, needle: str) -> bool:
    """그 낱말이 **단정으로** 쓰였나 --- 줄 단위로 본다(노트 697).

    **문자열 검사는 범위를 정해야 한다.** 노트 674(부분 문자열) · 677(숫자
    경계) · 693(이름 범위) 에 이어 네 번째 자리이고, 이번엔 **문맥**이다.
    모형이 *``지금까지 ○○% 적중했다 는 말할 수 없습니다''* 라고 카드를 지키는
    문장을 썼는데 검사가 그것을 위반으로 셌다 --- 규율을 지킨 답에 경고를
    붙이면 다음 사람이 경고를 무시하게 된다.

    가르는 방법: 그 낱말이 있는 **줄**에 부인/예시 낱말이 같이 있거나 낱말이
    따옴표 안에 있으면 단정이 아니다.

    **한계**: 줄 단위이므로 부인이 앞 줄에 있고 단정이 다음 줄이면 놓친다.
    문장 단위 판정은 문장 경계 판정이 필요하고 그것이 한글에서 또 다른
    범위 문제다 --- 그래서 **거친 자임을 적어 둔다.**
    """
    for line in text.splitlines():
        if needle not in line:
            continue
        if any(n in line for n in NEGATION):
            continue
        i = line.index(needle)
        near = line[max(0, i - 30):i + len(needle) + 8]
        if any(q in near for q in ('"', "'", "\u201c", "\u201d", "「", "『", "``")):
            continue
        return True
    return False


#: **이름 붙인 구간**을 잡는 무늬. 낱말 하나("구간")로는 부족했다 ---
#: `80% 확률로 8천~2만명` 이 안 걸렸다. 이름 붙인 구간은 표현이 여러 개이므로
#: **두 조각이 같은 줄에 있는지**로 잡는다: ① 신뢰 수준(`80%` 꼴) ② 범위 표시.
LEVEL = re.compile(r"(?<!\d)(7\d|8\d|9\d)\s*%\s*(구간|확률|신뢰|믿음)")
RANGE = re.compile(r"[~∼〜]|[-–—]\s*\d|사이|부터.*까지")


def check(text: str) -> list:
    """답에 금지 꼴이 **단정으로** 섞였나 --- 배급 전 자기 검사(거친 자다).

    문자열 검사는 범위를 정해야 한다(노트 677 · 693 · 697). 여기서는
    `_asserted` 가 부인·예시·따옴표 자리를 걸러 낸다.
    """
    hits = []
    if "실측" not in text:
        for line in text.splitlines():
            m = LEVEL.search(line)
            if not m:
                continue
            if not (RANGE.search(line) or "구간" in line):
                continue
            if any(n in line for n in NEGATION):
                continue
            i = m.start()
            if any(q in line[max(0, i - 30):i + 40]
                   for q in ('"', "'", "\u201c", "\u201d", "「", "『")):
                continue
            hits.append(
                "이름 붙인 구간 --- **그 작품의** 구간은 실측 덮음 0.40 이다"
                "(노트 791). **그 도메인의** 구간(학습 라벨 10~90분위)은 덮음"
                " 0.8448 로 쓸 수 있다(노트 792) --- 어느 쪽인지 이름으로 갈라라")
            break
    if any(_asserted(text, w) for w in ("적중했", "적중률은", "적중률이")):
        hits.append("전향 실적 주장 --- 전향 기록 0건")
    return hits


