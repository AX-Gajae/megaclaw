def names() -> list:
    return [c["이름"] for c in CAPS]


def measured() -> list:
    """등록소의 모든 자 --- 능력 카드의 '측정' 절이 여기서 나온다."""
    out, seen = [], set()
    for c in CAPS:
        for note, what, val in c["자"]:
            k = (note, what)
            if k in seen:
                continue
            seen.add(k)
            out.append({"노트": note, "무엇": what, "값": val})
    return sorted(out, key=lambda x: -x["노트"])


def tool_schemas() -> list:
    """`agent` 가 API 에 넘기는 꼴 --- 이름·설명·입력만."""
    return [{"name": c["이름"], "description": c["설명"], "input_schema": c["입력"]}
            for c in CAPS]


def fns() -> dict:
    """이름 → 부르기."""
    return {c["이름"]: c["부르기"] for c in CAPS}


def check() -> dict:
    """등록소 자신을 검사한다 --- 규율 넷이 지켜졌나."""
    bad = []
    for c in CAPS:
        if not c["이름"].replace("_", "").isalnum() or not c["이름"].isascii():
            bad.append(f"{c['이름']}: 이름이 ASCII 가 아니다(노트 693)")
        if not c.get("자"):
            bad.append(f"{c['이름']}: **자가 없다** --- 자 없는 능력은 등록할 수 없다")
        for note, what, _v in c.get("자", []):
            if not isinstance(note, int) or note <= 0:
                bad.append(f"{c['이름']}: 자 '{what}' 에 노트 번호가 없다")
        if not c.get("산출"):
            bad.append(f"{c['이름']}: `산출` 이 없다 --- 기록인지 지금 계산인지 밝혀야 한다")
        if not callable(c.get("부르기")):
            bad.append(f"{c['이름']}: 부를 수 없다")
    dup = [n for n in names() if names().count(n) > 1]
    if dup:
        bad.append(f"이름이 겹친다: {sorted(set(dup))}")
    return {"검사": "등록소 규율 넷", "능력": len(CAPS), "통과": not bad,
            "걸린 곳": bad or "없음"}


