# 지연 임포트 --- 등록소가 무거운 모듈을 끌고 오지 않게
def _research_seal(seal: str = "") -> dict:
    """봉인 파일을 읽는다. **없으면 없다고 말한다** --- 지어내지 않는다."""
    from pathlib import Path as _P
    d = _P(__file__).resolve().parents[1] / "data/lab/research"
    if not d.exists():
        return {"있나": False, "말": "아직 조사를 한 번도 안 돌렸다"}
    fs = sorted(d.glob(f"seal_{seal or ''}*.json"),
                key=lambda p: p.stat().st_mtime, reverse=True)
    if not fs:
        return {"있나": False, "말": f"'{seal}' 봉인이 없다",
                "있는 것": [x.stem for x in sorted(d.glob("seal_*.json"))][-5:]}
    import json as _j
    return {"있나": True, **_j.loads(fs[0].read_text())}


