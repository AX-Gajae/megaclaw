# ── 조립 ──────────────────────────────────────────────────────────
def event_brief(event=None, ctx: dict | None = None) -> dict:
    """이벤트 하나 → **다섯 절.** 절마다 `상태`·`값`·`자`·`왜`·`무엇이 생기면 잰다`.

    🔴 세 겹으로 막는다:
      ① 추정기의 **최대상태** --- ③④⑤ 는 「못 잼」을 못 넘는다
      ② `layers.verify()` --- 계약을 어긴 조립물은 `조립 검사` 에 걸려 실린다
      ③ `layers.gate()` --- 금지 꼴 다섯을 **조립 단계에서** 건다(L6 전에)

    셋 다 **조용히 고치지 않는다**(노트 133). 걸린 것을 반환에 실어 보낸다.
    """
    t0 = time.time()
    ctx = dict(ctx or {})
    ev = normalize(event)
    절 = []
    for out in ("①우려", "②결과", "③시점", "④개선", "⑤파생"):
        e = layers.estimator(out)
        try:
            s = e["부르기"](ev, ctx)
        except Exception as ex:               # 추정기가 터지면 **못 읽음**이다
            s = {"상태": "못 읽음",
                 "왜": f"추정기 `{e['이름']}` 이 터졌다: {type(ex).__name__}: {ex}",
                 "무엇이 생기면 잰다": "그 예외를 고치면 다시 잰다"}
        s = {"절": out, "무엇": layers.OUTPUTS[out], "층": e["층"],
             "최대상태": e["최대상태"], "추정기": e["이름"],
             "값": None, "자": None, **s}
        if s["상태"] != "측정됨":
            s["값"] = None                    # 못 잰다면서 값을 들고 있으면 안 된다
            s.setdefault("자", None)
            s["왜 못 잼" if s["상태"] == "못 잼" else "왜 못 읽음"] = s["왜"]
        else:
            s.setdefault("산출", "지금 계산")
        절.append(s)
    b = {
        "무엇": "이벤트 하나에 대한 다섯 절 --- `docs/목표.md` 의 다섯 출력",
        "이벤트": ev,
        "절": 절,
        "요약": {s["절"]: s["상태"] for s in 절},
        "🔴 오늘 0 인 절": {
            "③시점": "이벤트 표 없음 + 상태 장은 전체 변동의 0.236%(노트 769·910)",
            "④개선": f"{NO_INTERVENTION} --- A등급 효과가 위약 한복판(노트 903)",
            "⑤파생": "합류점 0개(노트 897 · 파이썬 604개 전수 AST)"},
        "층": [{"층": L["층"], "이름": L["이름"], "오늘": L["오늘"]}
              for L in layers.LAYERS],
    }
    b["조립 검사"] = layers.verify(b) or "통과"
    b["금지 꼴 게이트"] = layers.gate(b) or "걸린 것 없음"
    b["초"] = round(time.time() - t0, 3)
    return b


def main() -> None:
    arg = " ".join(sys.argv[1:]).strip()
    print(json.dumps(event_brief(arg or None), ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
