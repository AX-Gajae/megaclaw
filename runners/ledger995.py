def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--den", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--score", default=str(ROOT / "runners/out995_score.json"))
    ap.add_argument("--docsha", default=str(ROOT / "runners/out995_docsha.json"))
    ap.add_argument("--fiveprime", default=None)
    ap.add_argument("--pr", type=int, default=None)
    ap.add_argument("--tip", default=None)
    ap.add_argument("--tipdiff-corr", default=None,
                    help="🔴 커밋 «뒤»에 기계로 «잰» 잔여 경로 목록(정정 항목이 된다)")
    ap.add_argument("--tipdiff", default=None,
                    help="🔴 push 된 가지 끝과 `--tree` 사이에 남는 경로 목록(쉼표로)")
    a = ap.parse_args(argv)

    den = _load(a.den)
    n0 = len(den)
    S, D = _load(a.score), _load(a.docsha)
    fp = _load(a.fiveprime) if a.fiveprime else None
    E = entries(S, D, fp, a.pr, a.tip,
                [x for x in (a.tipdiff or "").split(",") if x],
                [x for x in (getattr(a, "tipdiff_corr", None) or "").split(",") if x])

    dup = [k for k in E if k in den]
    if dup:
        raise SystemExit("🔴 옛 항목을 덮을 뻔했다(추가만 한다): %r" % dup)
    for k, v in E.items():
        den[k] = v
    if a.pr is not None:
        den["🔴 노트 995 — PR 번호와 가지 끝 sha"]["🔴 원장 항목 수(이 커밋 뒤)"] = len(den)
    with open(a.out, "w", encoding="utf-8") as f:
        json.dump(den, f, ensure_ascii=False, indent=1)
    sys.stdout.write("원장 %d → %d (새 항목 %d) · %s\n" % (n0, len(den), len(E), a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
