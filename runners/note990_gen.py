def _now():
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def table(ref):
    vals, paths, errs = collections.OrderedDict(), collections.OrderedDict(), \
        collections.OrderedDict()
    for name, path in SPEC.items():
        v, err = LG.resolve(path)
        paths[name] = path
        if err is None:
            vals[name] = v
        else:
            vals[name] = None
            errs[name] = err
    t = collections.OrderedDict([
        ("ref", ref),
        ("🔴 슬롯 수", len(SPEC)),
        ("🔴 못 읽은 슬롯 수", len(errs)),
        ("🔴 못 읽은 슬롯", errs),
        ("값", vals), ("키 경로", paths),
        ("🔴 이 표의 규율",
         "🔴 **여기 없는 수는 문서에 «못 들어간다».** 각 슬롯은 «키 경로»를 나르고 "
         "문서를 찍을 때 «문자 자리»가 `out990_slots.json` 에 남는다"),
        ("🔴 걸린 자리(= 자가 «비교»를 «수행»한 회수)", len(SPEC)),
        ("통과", bool(not errs)),
    ])
    return t


SLOT = re.compile(r"\{\{([^}]+)\}\}")


def render(tpl, t):
    """🔴 치환하며 «슬롯이 앉은 문자 자리»를 기록한다."""
    vals, paths = t["값"], t["키 경로"]
    out, slots, i = [], [], 0
    pos = 0
    for m in SLOT.finditer(tpl):
        k = m.group(1).strip()
        if k not in vals:
            raise SystemExit("🔴 치환표에 없는 슬롯: %s" % k)
        out.append(tpl[i:m.start()])
        pos += m.start() - i
        s = LG.render(vals[k]) if vals[k] is not None else "없음"
        slots.append({"키 경로": paths[k], "값": s, "슬롯": k,
                      "시작": pos, "끝": pos + len(s)})
        out.append(s)
        pos += len(s)
        i = m.end()
    out.append(tpl[i:])
    return "".join(out), slots


