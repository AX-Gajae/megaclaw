def table_sha(T):
    return hashlib.sha256(
        json.dumps(T, ensure_ascii=False, sort_keys=True).encode("utf-8")).hexdigest()


PAT = re.compile(r"⟦([^⟧]+)⟧")


def fill(tmpl, T):
    missing = []

    def sub(m):
        k = m.group(1)
        if k not in T:
            missing.append(k)
            return "⟦???⟧"
        v = T[k]
        if isinstance(v, bool):
            return "true" if v else "false"
        if v is None:
            return "없음"
        if isinstance(v, list):
            return " · ".join(str(x) for x in v) if v else "없음"
        return str(v)

    s = PAT.sub(sub, tmpl)
    if missing:
        raise SystemExit("🔴 치환표에 없는 슬롯 %d 개: %s" % (len(missing), missing[:10]))
    return s


