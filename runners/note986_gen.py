def stage_card():
    """🔴🔴 **R4 --- 「덧붙임」이 아니라 「치환」이다.**

    `note985_gen.py:978` 은 `rest`(이전 파일 전량)를 뒤에 붙여
    **`--stage card` 마다 한 벌씩 쌓였다**(985 카드 **28 벌** · 파일의 **21%**).
    986 판은 **자기 표지(`MEMO_A` ~ `MEMO_B`) 구획만 갈아 끼운다** ---
    두 번 돌려도 파일이 안 자란다.
    """
    body = HAND.read_text(encoding="utf-8")
    sha = hashlib.sha256(body.encode("utf-8")).hexdigest()
    head = (
        "%s\n## 🔴🔴🔴 지금 여기부터 — **노트 986 이 끝났다**\n\n"
        "> 🔴🔴🔴 **아래는 `docs/handoff_986.md` 를 «바이트로» 옮긴 것이다.**\n"
        "> `sha256 = %s`\n"
        "> 🔴 **손으로 안 썼다** --- `runners/note986_gen.py --stage card` 가 옮겼다.\n"
        "> 🔴🔴 **986 R4: 이 쓰기는 「덧붙임」이 아니라 「치환」이다** --- 표지 구획만 "
        "갈아 끼우므로 두 번 돌려도 파일이 «안 자란다»(985 는 28 벌 쌓였다).\n\n"
        % (MEMO_A, sha))
    block = head + body + "\n" + MEMO_B + "\n"
    old = MEMO.read_text(encoding="utf-8") if MEMO.is_file() else ""
    if MEMO_A in old and MEMO_B in old:
        i, j = old.index(MEMO_A), old.index(MEMO_B) + len(MEMO_B) + 1
        new = old[:i] + block + old[j:]
        mode = "치환(표지 구획을 갈아 끼웠다)"
    else:
        h1 = "# 실험실 인계 카드\n"
        rest = old[len(h1):] if old.startswith(h1) else old
        new = h1 + "\n" + block + "\n---\n" + rest
        mode = "첫 삽입(표지를 새로 박았다)"
    MEMO.write_text(new, encoding="utf-8")
    return {"모드": mode, "handoff sha256": sha, "옛 글자 수": len(old),
            "새 글자 수": len(new), "🔴 자랐나": len(new) > len(old)}


