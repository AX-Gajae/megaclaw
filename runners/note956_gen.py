                    ("🔴 D_문서 = ⓑ ÷ ②", b, n2, "ⓑ 맞은 FineWeb 문서", "② FineWeb 문서"),
                    ("🔴 D_키 = ⓐ ÷ ④", a, n4, "ⓐ 교집합 키", "④ FineWeb 서로 다른 키"),
