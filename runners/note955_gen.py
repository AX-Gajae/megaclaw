def crosscheck(d):
    """🔴 티처 #93 C1 의 교훈을 기계로 만든다 --- **키 이름과 실제 계산이 같은가.**

    산출물의 `D_*` 값을 **그 이름이 말하는 분자·분모로 직접 다시 나눠** 견준다.
    954 는 이 대조가 없어서 「교집합 ÷ FineWeb 표본 문서」라는 이름 밑에
    `fw_doc_hit / len(fwa)` 가 앉아 있었다.
    """
    rows = []
    for label, r in d["🔴 자별"].items():
        a = r["분자 ⓐ 교집합(서로 다른 키)"]
        b = r["분자 ⓑ 맞은 FineWeb 표본 문서"]
        c = r["분자 ⓒ 맞은 HPLT 문서"]
        n1 = r["분모 ① HPLT 문서 전량"]
        n2 = r["분모 ② FineWeb 표본 문서"]
        n3 = r["분모 ③ HPLT 서로 다른 키"]
        n4 = r["분모 ④ FineWeb 표본 서로 다른 키"]
        for key, num, den, nm_num, nm_den in [
                ("🔴 D_키 = ⓐ ÷ ④", a, n4, "ⓐ 교집합 키", "④ FineWeb 서로 다른 키"),
                ("🔴 D_문서 = ⓑ ÷ ②", b, n2, "ⓑ 맞은 FineWeb 문서", "② FineWeb 표본 문서"),
                ("🔴 D_954글자 = ⓐ ÷ ② (🔴 키÷문서 --- 단위가 다르다 · 판정 밖)",
                 a, n2, "ⓐ 교집합 키", "② FineWeb 표본 문서"),
                ("🔴 E_키 = ⓐ ÷ ③", a, n3, "ⓐ 교집합 키", "③ HPLT 서로 다른 키"),
                ("🔴 E_문서 = ⓒ ÷ ①", c, n1, "ⓒ 맞은 HPLT 문서", "① HPLT 문서 전량")]:
            got = r[key]
            want = round(num / den, 6)
            rows.append({"자": label, "키": key,
                         "이름이 말하는 분자": nm_num, "이름이 말하는 분모": nm_den,
                         "직접 다시 나눈 값": want, "산출물의 값": got,
                         "통과": bool(abs(got - want) < 1e-9)})
    # 절단 곡선도 같은 방식으로 --- 분자·분모가 같은 자리에 적혀 있다
    for label, r in d["🔴 자별"].items():
        for K, cu in r["🔴 절단 곡선"].items():
            got = cu["🔴 D_문서^K"]
            want = round(cu["🔴 D_문서^K 분자 = 다중도<=K 인 교집합 키에 걸린 FineWeb 표본 문서"]
                         / cu["🔴 D_문서^K 분모 = FineWeb 표본 문서"], 6)
            rows.append({"자": label, "키": "절단 %s · D_문서^K" % K,
                         "이름이 말하는 분자": "다중도<=K 인 교집합 키에 걸린 FineWeb 문서",
                         "이름이 말하는 분모": "FineWeb 표본 문서",
                         "직접 다시 나눈 값": want, "산출물의 값": got,
                         "통과": bool(abs(got - want) < 1e-9)})
    return {
        "무엇": "🔴 키 이름 대 실제 계산 --- 이름이 말하는 분자·분모로 직접 다시 나눠 견줬다",
        "왜": ("티처 #93 C1 --- 「생산기가 찍었다」는 경로를 보증하지 분자를 보증하지 않는다. "
              "954 는 이 대조가 없어서 잘못된 키 이름이 표·PR·원장·카드로 자동 전파됐다"),
        "분자 = 맞은 대조": sum(1 for r in rows if r["통과"]),
        "분모 = 대조 전량": len(rows),
        "🔴 어긋난 것": [r for r in rows if not r["통과"]],
        "통과": bool(all(r["통과"] for r in rows)),
    }


