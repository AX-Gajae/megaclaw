def G(obj, *path):
    cur = obj
    for k in path:
        cur = cur[k] if not isinstance(cur, list) else cur[k]
    return cur


def fmt(v):
    if isinstance(v, bool):
        return "참" if v else "거짓"
    if isinstance(v, float):
        return repr(v)                      # 🔴 왕복 정밀도 --- 반올림해서 싣지 않는다
    if isinstance(v, (list, tuple)):
        return ", ".join(fmt(x) for x in v)
    return str(v)


