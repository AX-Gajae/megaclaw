def stage_gen(ref=""):
    t0 = LG.now()
    cs0 = LG.code_stamp(RAN)
    man = collections.OrderedDict()
    for rel, fn in TARGETS:
        d = Doc()
        fn(d)
        p = ROOT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(d.text(), encoding="utf-8")
        man[rel] = {"절대경로": str(p), "슬롯 수": len(d.slots), "슬롯": d.slots}
    out = {"무엇": "978 — 본문 다섯의 슬롯 대장(어느 수가 어느 키 경로에서 왔나)",
           "언제": LG.now(),
           "🔴 대상": [t[0] for t in TARGETS],
           "🔴 분모: 본문 파일": len(TARGETS),
           "🔴 슬롯 합": sum(v["슬롯 수"] for v in man.values()),
           "통과": bool(all(v["슬롯 수"] > 0 for v in man.values())),
           "파일별": man}
    out["🔴 도장"] = LG.stamp_block(ref, cs0, LG.code_stamp(RAN), t0, RAN, LG.DATA)
    (OUT / "out978_slots.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    return {k: v for k, v in out.items() if k != "파일별"}


def stage_cardcheck(card):
    blk = (ROOT / "docs/card_978.md").read_text(encoding="utf-8")
    src = Path(card).read_text(encoding="utf-8")
    return {"🔴 카드 경로": card, "🔴 블록 글자 수": len(blk),
            "🔴🔴 카드가 블록을 글자 그대로 담고 있나": blk.strip() in src}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", required=True, choices=["gen", "cardcheck"])
    ap.add_argument("--card", default="")
    ap.add_argument("--ref", default="")
    a = ap.parse_args()
    r = stage_gen(a.ref) if a.stage == "gen" else stage_cardcheck(a.card)
    print(json.dumps(r, ensure_ascii=False, indent=1))
    return 0


