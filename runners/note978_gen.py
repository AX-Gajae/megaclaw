class Doc(object):
    """슬롯을 채우면서 **문자 위치**를 같이 적는다."""

    def __init__(self):
        self.buf, self.slots, self.n = [], [], 0

    def t(self, s):
        self.buf.append(s)
        self.n += len(s)
        return self

    def s(self, path):
        v, err = LG.resolve(path)
        if err is not None:
            raise SystemExit("🔴 키 경로가 안 풀린다: %s --- %s" % (path, err))
        txt = LG.render(v)
        self.slots.append({"키 경로": path, "값": txt,
                           "시작": self.n, "끝": self.n + len(txt)})
        self.buf.append(txt)
        self.n += len(txt)
        return self

    def text(self):
        return "".join(self.buf)


