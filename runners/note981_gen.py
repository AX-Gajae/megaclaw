# 🔴 채우기 — ⟦슬롯⟧ 이 표에 없으면 **터진다**(fail-closed)
# ══════════════════════════════════════════════════════════════════════
PAT = re.compile(r"⟦([^⟧]+)⟧")


def fill(tmpl, T):
    missing = []

    def sub(m):
        k = m.group(1)
        if k not in T:
            missing.append(k)
            return "⟦???⟧"
        v = T[k]
        if isinstance(v, bool):
            return "true" if v else "false"
        if v is None:
            return "없음"
        return str(v)

    s = PAT.sub(sub, tmpl)
    if missing:
        raise SystemExit("🔴 치환표에 없는 슬롯 %d 개: %s" % (len(missing), missing[:10]))
    return s


