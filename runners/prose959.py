def power() -> dict:
    """🔴 **등록된 수 그 자리**를 흔들어 대조기가 무는지 본다."""
    doc = ROOT / D
    bk = Path("/tmp/959_backup.md")
    shutil.copy(doc, bk)
    caught, rows = 0, []
    try:
        for c in CLAIMS_959:
            if "형식" not in c:
                continue
            src = json.loads((ROOT / c["산출물"]).read_text())
            fmt = c["형식"].format(dig(src, c["키"]))
            m = re.search(r"\d", fmt)
            if not m:
                continue
            bad = fmt[:m.start()] + str((int(m.group()) + 3) % 10) + fmt[m.start() + 1:]
            s = c["문장"]
            bads = s.replace(fmt, bad)
            if bads == s:
                rows.append({"키": c["키"], "🔴": "형식본이 문장 안에 없다", "잡았나": None})
                continue
            (doc).write_text(bk.read_text().replace(s, bads))
            red = not check(CLAIMS_959, stdout=False)["통과"]
            caught += int(red)
            rows.append({"키": c["키"], "형식본": fmt, "흔든 것": bad, "잡았나": red})
    finally:
        shutil.copy(bk, doc)
    n = sum(1 for r in rows if r["잡았나"] is not None)
    return {"🔴 분자: 붉게 잡은 것": caught, "🔴 분모: 흔든 주장": n,
            "주장별": rows, "통과": caught == n and n > 0}


def main() -> dict:
    r = check(CLAIMS_959)
    r["🔴 안 등록한 것"] = 안_등록한_것
    if "--power" in sys.argv:
        r["🔴 검정력(등록된 수 그 자리를 흔든다)"] = power()
    OUT.write_text(json.dumps(r, ensure_ascii=False, indent=1))
    return r


if __name__ == "__main__":
    sys.exit(0 if main()["통과"] else 1)
