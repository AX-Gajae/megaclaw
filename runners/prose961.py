def power(claims: list[dict]) -> dict:
    """🔴 **검정력** — 등록된 수를 그 자리에서 흔들면 대조기가 정말 붉어지나.

    흔드는 법: 기대 불리언은 뒤집고, 형식 문자열은 마지막 숫자를 1 늘린다.
    🔴 **안 붉어지는 주장은 「대조하고 있다」가 거짓인 주장이다.**
    """
    import re
    rows = []
    for c in claims:
        bad = dict(c)
        if "기대" in c:
            bad["기대"] = not c["기대"]
        else:
            m = list(re.finditer(r"\d", c["문장"]))
            if not m:
                rows.append({"문장": c["문장"], "흔들었나": False,
                             "결과": "🔴 흔들 숫자가 없다", "통과": False})
                continue
            i = m[-1].start()
            bad["문장"] = c["문장"][:i] + str((int(c["문장"][i]) + 1) % 10) + c["문장"][i + 1:]
        r = check([bad], stdout=False)["주장"][0]
        rows.append({"문장": c["문장"], "흔든 문장": bad.get("문장"),
                     "흔든 기대": bad.get("기대"),
                     "🔴 흔드니 붉어졌나": not r["통과"], "통과": not r["통과"]})
    return {"🔴 무엇": "등록된 수를 흔들면 대조기가 붉어지나 — 안 붉어지면 그 주장은 안 대조되고 있다",
            "분자: 흔드니 붉어진 주장": sum(1 for r in rows if r["통과"]),
            "분모: 등록한 주장": len(rows), "주장": rows,
            "통과": all(r["통과"] for r in rows)}


