def power() -> dict:
    """🔴 **등록된 수 그 자리**를 흔들어 대조기가 무는지 본다.

    ⚠ 🔴 **959 의 검정력 하네스는 날 글자로 맞대서** `2,050` 대 `2050` 같은 자릿점 ·
    유니코드 빼기표(`−`) 앞에서 **「형식본이 문장 안에 없다」로 그냥 넘어갔다**.
    대조기 자신은 `norm()` 을 쓰는데 검정력만 안 썼다 — **못 흔든 칸은 검정력이 0 이다**.
    960 은 **양쪽 다 `norm()` 을 통과시킨 뒤** 흔든다.
    """
    doc = ROOT / D
    bk = Path("/tmp/960_backup.md")
    shutil.copy(doc, bk)
    base = norm(bk.read_text())
    caught, rows = 0, []
    try:
        for c in CLAIMS_960:
            if "형식" not in c:
                continue
            src = json.loads((ROOT / c["산출물"]).read_text())
            fmt = norm(c["형식"].format(dig(src, c["키"])))
            m = re.search(r"\d", fmt)
            if not m:
                continue
            bad = fmt[:m.start()] + str((int(m.group()) + 3) % 10) + fmt[m.start() + 1:]
            s = norm(c["문장"])
            bads = s.replace(fmt, bad)
            if bads == s:
                rows.append({"키": c["키"], "🔴": "형식본이 문장 안에 없다", "잡았나": None})
                continue
            doc.write_text(base.replace(s, bads))
            red = not check(CLAIMS_960, stdout=False)["통과"]
            caught += int(red)
            rows.append({"키": c["키"], "형식본": fmt, "흔든 것": bad, "잡았나": red})
    finally:
        shutil.copy(bk, doc)
    n = sum(1 for r in rows if r["잡았나"] is not None)
    return {"🔴 분자: 붉게 잡은 것": caught, "🔴 분모: 흔든 주장": n,
            "주장별": rows, "통과": caught == n and n > 0}


def main() -> dict:
    r = check(CLAIMS_960)
    r["🔴 안 등록한 것"] = 안_등록한_것
    if "--power" in sys.argv:
        r["🔴 검정력(등록된 수 그 자리를 흔든다)"] = power()
    OUT.write_text(json.dumps(r, ensure_ascii=False, indent=1))
    return r


