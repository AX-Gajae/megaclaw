def norm(s: str) -> str:
    """🔴 **정규화 대조**(956 R3 의 교훈) — 활자만 다른 것을 「다르다」로 세지 않는다.

    · 유니코드 빼기표(U+2212) → ASCII `-`
    · 자릿점 `1,063` → `1063` (숫자 사이의 쉼표만)
    """
    import re
    s = s.replace("−", "-")
    return re.sub(r"(?<=\d),(?=\d)", "", s)


def dig(d, path):
    """🔴 958 수리 — 경로를 **리스트로도** 받는다.

    옛 판은 `path.split("/")` 뿐이라 **키 이름에 `/` 가 들어 있으면 원리상 못 찾는다**
    (958 의 산출물 키 `§6 자 A · 고정 모형 within/between` 이 실제로 그랬고, 대조기가
    「키가 없다」를 15번 냈다). 🔴 **자기 문법이 못 보는 자리를 자기가 신고하지 못했다.**
    """
    cur = d
    for k in (path if isinstance(path, (list, tuple)) else path.split("/")):
        cur = cur[k]
    return cur


def read_doc(rel: str) -> str:
    """🔴 958 수리 — **사정권을 넓힌다**(티처 #96 M3 · 2순위 ⓓ).

    957 의 이 자는 `docs/판정/957.md` **하나만** 봤다. 그래서 티처가 잡은 **틀린 수 여섯이
    전부 미등록 문장**이었고 그중 여럿이 **원장 안**에 있었다 — 대조기가 **원리상 안 본 자리**다.
    이제 `.json`(원장 · ⑤′ 산출물 · 배선 산출물)도 문서로 읽는다.
    """
    p = ROOT / rel
    if p.suffix == ".json":
        return norm(json.dumps(json.loads(p.read_text()), ensure_ascii=False))
    return norm(p.read_text())


def check(claims: list[dict], stdout: bool = True) -> dict:
    docs: dict[str, str] = {}
    rows = []
    for c in claims:
        doc = docs.setdefault(c["문서"], read_doc(c["문서"]))
        src = json.loads((ROOT / c["산출물"]).read_text())
        try:
            v = dig(src, c["키"])
        except (KeyError, TypeError):
            rows.append({**{k: c[k] for k in ("문서", "산출물", "키", "문장")},
                         "결과": "🔴 키가 없다", "통과": False})
            continue
        문장 = norm(c["문장"])
        in_doc = 문장 in doc
        if isinstance(v, bool):
            ok_val = (v == c["기대"])
            rows.append({"문서": c["문서"], "키": c["키"], "문장": c["문장"],
                         "산출물 값": v, "기대": c["기대"],
                         "문장이 문서에 있다": in_doc,
                         "결과": ("🟢" if (ok_val and in_doc) else "🔴"),
                         "통과": bool(ok_val and in_doc)})
        else:
            s = norm(c["형식"].format(v))
            rows.append({"문서": c["문서"], "키": c["키"], "문장": c["문장"],
                         "산출물 값": v, "형식본": s,
                         "형식본이 문장 안에 있다": s in 문장,
                         "문장이 문서에 있다": in_doc,
                         "결과": ("🟢" if (s in 문장 and in_doc) else "🔴"),
                         "통과": bool(s in 문장 and in_doc)})
    res = {
        "무엇": "🔴 산문 주장 대 산출물 키 대조 (티처 #95 C1)",
        "분자: 통과한 주장": sum(1 for r in rows if r["통과"]),
        "분모: 등록한 주장": len(rows),
        "🔴 이 자가 못 보는 것": "등록 안 한 문장은 원리상 안 본다 — 「전부 초록」이 「거짓이 없다」가 아니다",
        "주장": rows,
        "통과": all(r["통과"] for r in rows),
    }
    if stdout:
        print(json.dumps({k: v for k, v in res.items() if k != "주장"},
                         ensure_ascii=False, indent=1))
        for r in rows:
            if not r["통과"]:
                print(json.dumps(r, ensure_ascii=False))
    return res


