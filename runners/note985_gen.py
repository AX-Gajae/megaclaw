def stage_card():
    """🔴 **메모리 카드** --- `docs/handoff_985.md` 를 «바이트로» 옮긴다(규칙 D · 손 전사 0)."""
    body = HAND.read_text(encoding="utf-8")
    sha = hashlib.sha256(body.encode("utf-8")).hexdigest()
    old = MEMO.read_text(encoding="utf-8") if MEMO.is_file() else ""
    head = (
        "# 실험실 인계 카드\n\n"
        "## 🔴🔴🔴 지금 여기부터 — **노트 985 가 끝났다** (2026-08-17)\n\n"
        "> 🔴🔴🔴 **아래 「인계 카드 — 노트 985」 절은 `docs/handoff_985.md` 를 "
        "«바이트로» 옮긴 것이다.**\n"
        "> `sha256 = %s`\n"
        "> 🔴 **손으로 안 썼다** — `runners/note985_gen.py --stage card` 가 옮겼고 "
        "`runners/score985.py` 의 반증조건 9 가 **저장소 안 넷·원장·이 카드 여섯이 같은 수를 "
        "적나**를 잰다.\n\n" % sha)
    rest = old.split("\n", 1)[1] if old.startswith("# 실험실 인계 카드") else old
    MEMO.write_text(head + body + "\n\n---\n" + rest, encoding="utf-8")
    return {"handoff sha256": sha, "메모리 카드": str(MEMO),
            "쓴 글자 수": len(head) + len(body) + len(rest) + 6}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", required=True, choices=["all", "card"])
    ap.add_argument("--ref", default="")
    a = ap.parse_args()
    if a.stage == "card":
        print(json.dumps(stage_card(), ensure_ascii=False))
        return 0
    print(json.dumps(stage_all(a.ref), ensure_ascii=False))
    return 0


