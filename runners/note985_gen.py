def _load(name, must=True):
    p = OUT / name
    if not p.is_file():
        if must:
            raise SystemExit("🔴 %s 가 없다 — fail-closed (규칙 D)" % name)
        return {}
    return json.loads(p.read_text(encoding="utf-8"))


def _res(obj, path):
    cur = obj
    for k in path:
        if isinstance(cur, dict) and k in cur:
            cur = cur[k]
        elif isinstance(cur, list) and isinstance(k, int) and -len(cur) <= k < len(cur):
            cur = cur[k]
        else:
            raise SystemExit("🔴 치환표 키 경로가 없다: %r (%r 에서 막혔다)" % (path, k))
    return cur


