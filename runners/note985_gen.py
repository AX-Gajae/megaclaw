def fill(tmpl, T):
    """🔴 **fail-closed** — 없는 슬롯과 `None` 값에 둘 다 터진다."""
    missing, nones = [], []

    def sub(m):
        k = m.group(1)
        if k not in T:
            missing.append(k)
            return "⟦???⟧"
        v = T[k]
        if v is None:
            if not k.startswith(tuple(NONE_OK)):
                nones.append(k)
                return "⟦None⟧"
            return "🔴 아직 안 돌았다"
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, list):
            return " · ".join(str(x) for x in v) if v else "🔴 비었다"
        return str(v)

    s = PAT.sub(sub, tmpl)
    if missing:
        raise SystemExit("🔴 치환표에 없는 슬롯 %d: %s" % (len(missing), missing[:10]))
    if nones:
        raise SystemExit("🔴🔴 fail-closed — `None` 슬롯 %d: %s" % (len(nones), nones[:10]))
    return s


