def _now():
    import datetime as dt
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def table(ref):
    """🔴 `SPEC` 전량을 «산출물에서» 따라간다. 못 읽은 것을 «수와 이름»으로 남긴다."""
    vals, paths, errs = collections.OrderedDict(), collections.OrderedDict(), {}
    for name, path in SPEC.items():
        v, err = LG.resolve(path)
        paths[name] = path
        if err is None:
            vals[name] = v
        else:
            vals[name] = None
            errs[name] = err
    return collections.OrderedDict([
        ("ref", ref),
        ("🔴 슬롯 수", len(SPEC)),
        ("🔴 못 읽은 슬롯 수", len(errs)),
        ("🔴 못 읽은 슬롯", errs or "없음"),
        ("값", vals), ("키 경로", paths),
        ("🔴 이 표의 규율",
         "🔴🔴🔴 **여기 «없는» 수도, 여기 «있지만 못 읽은» 수도 문서에 «못» 들어간다** --- "
         "`render()` 가 «둘 다»에서 멈춘다(993 `R1`). "
         "🔴 991 은 「키를 못 찾은 슬롯」을 조용히 `\"없음\"` 으로 찍었다"),
        ("🔴 걸린 자리(= 자가 «비교»를 «수행»한 회수)", len(SPEC)),
        ("통과", bool(not errs)),
    ])


SLOT = re.compile(r"\{\{([^}]+)\}\}")


def render(tpl, t, name=""):
    """🔴🔴🔴 치환하며 «슬롯이 앉은 문자 자리»를 기록한다.

    🔴 **993 `R1`** --- 「치환표에 «없는» 슬롯」에서도, 「키를 «못 찾은» 슬롯」에서도 «멈춘다».
    """
    vals, paths = t["값"], t["키 경로"]
    out, slots, i, pos = [], [], 0, 0
    for m in SLOT.finditer(tpl):
        k = m.group(1).strip()
        if k not in vals:
            raise SystemExit("🔴 치환표에 없는 슬롯: %s (%s)" % (k, name))
        if vals[k] is None:
            # 🔴🔴🔴 **993 `R1`** --- 991 은 여기서 조용히 `"없음"` 을 찍었다.
            raise SystemExit(
                "🔴🔴🔴 **키를 «못 찾은» 슬롯이다 --- 멈춘다**(993 `R1`): %s\n"
                "  문서: %s\n  키 경로: %s\n"
                "  🔴 991 은 여기서 조용히 「없음」을 찍었고 그래서 문서 넷이 "
                "「예측 「없음/없음」」을 실었다" % (k, name, " | ".join(paths[k])))
        out.append(tpl[i:m.start()])
        pos += m.start() - i
        s = LG.render(vals[k])
        slots.append({"키 경로": paths[k], "값": s, "슬롯": k,
                      "시작": pos, "끝": pos + len(s)})
        out.append(s)
        pos += len(s)
        i = m.end()
    out.append(tpl[i:])
    return "".join(out), slots


