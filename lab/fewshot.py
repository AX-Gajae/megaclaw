"""짝 라벨 **몇 건**으로 축 무게를 맞춘다(노트 587).

집 밖 짝에 챔피언을 그대로 물으면 앱은 $+0.5038$ 인데, 그 짝 자기 자료로
$5$겹 교차검증한 천장은 $+0.6177$ 이다. 남은 $0.11$ 은 **부호가 아니라
무게** 문제다 --- 노트 583 이 쟀듯이

    축 <-> 라벨          학습(가중)   KR 만화    비게임 앱
    target_breadth        +0.4163   +0.4831    +0.2141
    goods_scale           +0.3097   +0.5028    +0.3968
    entry_friction        -0.1051   -0.3202   **-0.6353**

**학습의 꼴찌가 앱의 일등이다.** 같은 축, 같은 부호, 다른 무게.

.. warning::

   **부호를 맞추는 것과 무게를 맞추는 것은 다른 층이다.**

   노트 443 ``calibrate_ooc`` 도, 노트 463 이 반증한 것도, 노트 582 가
   ``k=40 이 k=0 과 같다``로 닫은 것도 전부 **부호** 였다. 무게는 아무도
   안 재 봤고, 재니 앱이 $k{=}40$ 에서 $+0.0595$ $[+0.0346,+0.0845]$ 다.

   **"안 된다"는 무엇을 맞췄는지까지 적어야 한다.**

측정(노트 587 · 씨앗 12 · 노트 586 채택 위에서)::

    짝            k=0      k=20     k=40     k=80     k=160   천장
    비게임 앱   +0.5038  +0.5223  +0.5633  +0.5986  +0.6132  0.6177 (99%)
    KR 만화     +0.6824  +0.6586  +0.6837  +0.6972  +0.7030  0.7152 (98%)
    CN 만화     +0.3237  +0.2079  +0.3068  +0.3186  +0.2926  0.3619

**대조가 값을 한다** --- 같은 $k$ 건에 라벨을 섞어 주면 KR $-0.4501$ ·
앱 $-0.6560$ 으로 무너진다. 이득이 절차의 부산물이 아니다.

**세 가지를 미리 적어 둔다.**

1. **KR 은 이득이 없다**($+0.0013$, $0$ 을 문다). 이미 학습과 무게 순서가
   같아서 고칠 것이 없다. **약한 시장일수록 사례가 크게 돕는다.**
2. **$k$ 가 적으면 오히려 내려간다** --- KR 이 $k{=}20$ 에서 $+0.6824 \to
   +0.6586$ 이다. 무게 고르기 자체가 과적합한다(노트 584 가 전용 모형에서
   본 것과 같은 무늬). ``MIN_K`` 아래면 **보정을 안 한다.**
3. **채점 집합이 줄어든다** --- $k$ 건은 빼고 채점해야 한다. CN 은 $352$
   행뿐이라 $k{=}160$ 이면 $45\%$ 가 빠져 $k$ 끼리 견줄 수 없다.
   ``fit`` 은 쓴 인덱스를 돌려주므로 **호출한 쪽이 반드시 빼고 채점한다.**
"""
from __future__ import annotations

import numpy as np
from scipy.stats import rankdata
from sklearn.linear_model import RidgeCV

MIN_K = 40               # 이 아래면 보정을 안 한다(노트 587 --- k=20 은 손해)
# **상한도 있다**(노트 595). ``k`` 건은 채점에서 빼야 하므로 짝이 작으면
# **채점 집합이 통째로 달라진다** --- CN 만화(352행)에서 ``k=160`` 은
# 채점의 **45%** 를 가져간다. 노트 587 · 595 가 CN 에서 본 하락
# (k=40 -0.0466 · k=160 -0.0113)이 그것이다. **작은 짝이 하필 k 를 제일
# 필요로 하는데 쓸 수가 없다.**
MAX_FRAC = 0.15          # k 가 짝의 이 비율을 넘으면 경고한다
ALPHAS = (0.1, 1.0, 10.0, 100.0)
MIN_COV = 0.5            # 짝에서 이만큼도 관측 안 된 축은 안 쓴다


def usable_k(n: int) -> tuple[int, int]:
    """그 짝에서 쓸 수 있는 ``k`` 의 아래·위(노트 587 · 595).

    아래는 맞출 수 있는 최소치(``MIN_K``), 위는 **채점을 망가뜨리지 않는**
    최대치다. 둘이 뒤집히면(짝이 너무 작으면) ``(MIN_K, 0)`` 이 나오고,
    그것은 **이 짝에는 사례 보정을 쓸 수 없다**는 뜻이다."""
    return MIN_K, int(n * MAX_FRAC)


def design(pred, A, M, names, axes) -> np.ndarray:
    """[챔피언 예보, 짝이 관측하는 축들] 을 **순위**로 바꿔 쌓는다.

    순위로 바꾸는 까닭은 두 가지다 --- ① 축마다 눈금이 달라 그대로 쓰면
    능형이 큰 눈금에 끌린다 ② 채점이 순위 상관이라 단조 변환에 불변이므로
    **잃는 것이 없다.**"""
    cols = [rankdata(pred) / max(len(pred), 1)]
    for a in axes:
        if a not in names:
            continue
        j = names.index(a)
        ok = M[:, j] > 0
        if ok.mean() < MIN_COV:
            continue
        v = np.full(len(pred), 0.5)
        if ok.sum():
            v[ok] = rankdata(A[ok, j]) / ok.sum()
        cols.append(v)
    return np.column_stack(cols)


def fit(pred, A, M, names, axes, y, idx):
    """``idx`` 의 라벨만 보고 무게를 맞춘 예보를 돌려준다.

    돌려주는 것은 ``(보정된 예보, 쓴 인덱스, 무엇을 했나)`` 다.
    ``idx`` 가 ``MIN_K`` 보다 적으면 **보정하지 않고 원 예보를 그대로**
    돌려준다 --- 노트 587 이 그 구간에서 손해를 쟀다.

    **호출한 쪽이 ``쓴 인덱스`` 를 채점에서 빼야 한다.** 안 빼면 그 행들의
    라벨을 보고 맞춘 무게로 그 행들을 채점하는 것이다."""
    idx = np.asarray(idx, int)
    n = len(np.asarray(pred, float))
    lo, hi = usable_k(n)
    if len(idx) < lo:
        return np.asarray(pred, float), idx, "k=%d < MIN_K=%d --- 보정 안 함" % (len(idx), lo)
    warn = ""
    if len(idx) > hi:
        warn = ("  ⚠ k=%d 가 짝의 %.0f%% 다(문턱 %.0f%%) --- **채점 집합이 "
                "달라진다**(노트 595). 이 k 는 다른 k 와 견줄 수 없다."
                % (len(idx), 100.0 * len(idx) / max(n, 1), 100.0 * MAX_FRAC))
    X = design(np.asarray(pred, float), A, M, list(names), axes)
    yk = np.asarray(y, float)[idx]
    if not np.isfinite(yk).all() or len(np.unique(yk)) < 3:
        return np.asarray(pred, float), idx, "k건 라벨이 상수에 가깝다 --- 보정 안 함"
    g = RidgeCV(alphas=ALPHAS).fit(X[idx], rankdata(yk) / len(idx))
    return g.predict(X), idx, ("축칸 %d개 · alpha %.3g" % (X.shape[1], float(g.alpha_))) + warn


def note() -> str:
    """쓸 때 같이 찍는 경고(노트 561 · 568 · 584 규약)."""
    return "\n".join([
        "  ⚠ **무게 보정은 그 짝 라벨을 본다**(노트 587). 쓴 k건은 "
        "**반드시 채점에서 뺀다** --- 안 빼면 자기 라벨로 맞춘 무게로",
        "    자기를 채점하는 것이다. k 가 %d 아래면 보정이 **손해**다"
        "(KR k=20 에서 +0.6824 -> +0.6586)." % MIN_K,
        "    **이득은 그 시장이 학습과 얼마나 다른가에 비례한다** --- "
        "앱 +0.0595 · KR +0.0013(0 을 문다).",
    ])
