        ids = ids_all[dom]
        tags = []
        # 이 호출이 실제로 읽는 필드만 본다 --- 안 읽는 필드까지 세면
        # ``지웠다''는 기록이 거짓이 된다.
        here = set(lists) | set(singles)
        stale = {f: g for f, g in STALE.get(dom, {}).items() if f in here}
        nstale = 0
        for i in ids:
            v = byid.get(i) or {}
            # 상해 있는 칸은 그 행에서만 지운다(노트 547) --- 필드를 통째로
            # 빼면 깨끗한 행의 정보까지 버린다.
            bad = {f for f, flag in stale.items() if v.get(flag)}
            if bad:
                nstale += 1
            t = [f"{f[0]}:{x}" for f in lists if f not in bad
                 for x in (v.get(f) or [])]
            t += [f"{f[0]}:{v[f]}" for f in singles
                  if f not in bad and v.get(f) is not None]
            tags.append([x for x in t if not POSTHOC.search(str(x))])
        if nstale:
            STALE_HITS[f"{pre}_{dom}"] = (nstale, len(ids))
        yr = data.yr[dom]
        y = data.dom[dom][2]
        tr = np.isfinite(yr) & (yr < T) & np.isfinite(y)
        if tr.sum() < 100:
            return
        cnt = Counter(t for i, ts in enumerate(tags) if tr[i] for t in ts)
        keep = [t for t, n in cnt.items() if n >= MIN_TAG]
        if len(keep) < 8:
            return
        ix = {t: i for i, t in enumerate(keep)}
        X = np.zeros((len(ids), len(keep)))
        for i, ts in enumerate(tags):
            for t in ts:
                if t in ix:
                    X[i, ix[t]] = 1.0
        has = X.sum(1) > 0
        # **관측된 학습 행으로만 중심잡고 적합한다**(노트 266). 토큰이 하나도
        # 없는 행은 전부 0 이라, 중심을 뺀 뒤 그 행들이 **``기록됐나''라는
        # 방향**을 만든다. 애니 ``air_quarter``(덮음 85%)로 재 봤더니 마지막
        # 성분이 그 방향이었고(``기록됨''과 -0.63, 설명력 5.8%) 연도 통제
        # 상관 +0.285 에 조각 5/5 로 **검사를 통과했다.** 기록된 행 안에서만
        # 다시 재니 네 성분이 전부 |rho| < 0.07 이다 --- 신호가 통째로
        # 결측 무늬였다. 기록률이 학습 81.7% 대 유보 93.6% 로 다르고 그
        # ``기록됨''이 라벨과 +0.342 였기 때문이다.
        trO = tr & has
        if trO.sum() < 100:
            return
        Xc = X - X[trO].mean(0)
        _u, _s, vt = np.linalg.svd(Xc[trO], full_matrices=False)
        # ``matmul`` 이 ``divide by zero`` · ``overflow`` 를 띄운다(노트 273).
        # **행렬곱에는 나눗셈이 없다** --- numpy 의 SIMD 커널이 안 쓰는 레인에서
        # 부동소수 플래그를 세우는 알려진 잡음이고, 결과는 멀쩡하다(여섯 축 다
        # 유한 100\%, 값 범위 [0,1], 서로 다른 값 140$\sim$2,012). 토큰 행렬이
        # 순위 결손이라(원핫 열이 상수합) 특잇값에 7e-14 같은 것이 섞이는데
        # 그것도 투영에는 해가 없다.
        #
        # **좁게 막는다** --- 여기서만, 이 세 종류만. 넓게 막으면 나중에 진짜
        # 경고를 못 본다.
        with np.errstate(divide="ignore", over="ignore", invalid="ignore"):
            P = Xc @ vt.T                      # 유보는 투영만
        for j in comps:
            if j >= P.shape[1]:
                continue
            out[f"{pre}_c{j}_{dom}"] = {dom: _pct(P[:, j], has)}
