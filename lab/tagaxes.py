def _pct(v: np.ndarray, ok: np.ndarray) -> tuple:
    p = np.full(len(v), 0.5)
    if ok.sum() > 1:
        p[ok] = (rankdata(v[ok]) - 0.5) / ok.sum()
    return p, ok.astype(float)


